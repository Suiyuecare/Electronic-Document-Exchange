"""Deterministic, backend-only forwards; no live database access."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from tools.shared_supabase_bootstrap import ROOT, BUNDLE_VERSION, sha256_text, transform_sql

FORWARDS = {
    "seals": (
        "20261012114854_explicit_seal_owner_policy_and_continuous_geometry.sql",
        "20261012120530_shared_explicit_seal_owner_policy_and_continuous_geometry.sql",
        "20261011140824_complete_workflow_readiness_queries.sql",
    ),
    "application": (
        "20261012115431_editor_application_final_snapshot.sql",
        "20261012120531_shared_editor_application_final_snapshot.sql",
        "20261012114854_explicit_seal_owner_policy_and_continuous_geometry.sql",
    ),
}


def render_shared_forward(kind: str) -> str:
    source_name, _, prerequisite = FORWARDS[kind]
    source = (ROOT / "supabase/migrations" / source_name).read_text(encoding="utf-8")
    transformed = transform_sql(source)
    source_hash, transformed_hash = sha256_text(source), sha256_text(transformed)
    return f"""-- Generated by tools/editor_metadata_seal_shared_forward.py ({kind}).
-- Does not contact or modify Finance/HR tables or an exchange provider.
begin;
select pg_catalog.pg_advisory_xact_lock(1788103601,20261012);
do $editor_metadata_seal_forward$
begin
 if pg_catalog.to_regclass('edoc_private.shared_project_migration_ledger') is null
  or pg_catalog.to_regclass('edoc.company_seals') is null
  or not exists(select 1 from pg_catalog.pg_roles where rolname='edoc_backend' and not rolbypassrls)
  or not exists(select 1 from edoc_private.shared_project_migration_ledger where file_name='{prerequisite}') then
  raise exception 'shared_editor_metadata_seal_preflight_failed';
 end if;
 if exists(select 1 from edoc_private.shared_project_migration_ledger where file_name='{source_name}'
  and (source_sha256 is distinct from '{source_hash}' or transformed_sha256 is distinct from '{transformed_hash}')) then
  raise exception 'shared_editor_metadata_seal_source_hash_mismatch';
 end if;
 if not exists(select 1 from edoc_private.shared_project_migration_ledger where file_name='{source_name}') then
  execute $editor_metadata_seal_source$
{transformed}$editor_metadata_seal_source$;
  insert into edoc_private.shared_project_migration_ledger(file_name,source_sha256,transformed_sha256,bundle_version)
   values('{source_name}','{source_hash}','{transformed_hash}','{BUNDLE_VERSION}');
 end if;
end $editor_metadata_seal_forward$;
notify pgrst,'reload schema';
commit;
"""


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("kind", choices=tuple(FORWARDS))
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()
    rendered = render_shared_forward(args.kind)
    target = ROOT / "supabase/shared-project-migrations" / FORWARDS[args.kind][1]
    if args.check:
        matches = target.is_file() and target.read_text(encoding="utf-8") == rendered
        print(json.dumps({"matches": matches, "file": target.name}))
        raise SystemExit(0 if matches else 1)
    print(json.dumps({"file": str(target), "content": rendered}) if args.json else rendered, end="\n" if args.json else "")
