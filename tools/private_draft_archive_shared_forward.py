"""Deterministic backend-only shared-schema forward for private draft recovery."""
from tools.shared_supabase_bootstrap import ROOT, BUNDLE_VERSION, sha256_text, transform_sql

SOURCE = "20261018074142_private_draft_archive_restore.sql"
FORWARD_NAME = "20261018074142_shared_private_draft_archive_restore.sql"


def render_cutover_gate(schema="public"):
    """Read-only exact-code/privilege gate, shared by rollout and local tests."""
    if schema not in ("public", "edoc"):
        raise ValueError("private_draft_archive_schema_invalid")
    source = (ROOT / "supabase/migrations" / SOURCE).read_text()
    if schema == "edoc":
        source = transform_sql(source)
    archive_body = source.split(" as $$", 1)[1].split("$$;", 1)[0]
    catalog_body = source.split(" as $function$", 1)[1].split("$function$;", 1)[0]
    backend = "service_role" if schema == "public" else "edoc_backend"
    denied = "'anon','authenticated','authenticator'" + (",'service_role'" if schema == "edoc" else "")
    return f"""-- Private drafts: exact code, private ownership and backend-only access.
do $private_draft_archive_gate$
declare
 v_proc record; v_expected record; v_role text; v_save text;
begin
 for v_expected in select * from (values
  ('{schema}.edoc_archive_private_compose_draft(text,text,text,integer,boolean)','v','{sha256_text(archive_body)}'),
  ('{schema}.edoc_workspace_drafts(jsonb)','s','{sha256_text(catalog_body)}')
 ) as expected(signature,volatility,body_hash) loop
  select * into v_proc from pg_catalog.pg_proc where oid=pg_catalog.to_regprocedure(v_expected.signature);
  if not found then raise exception 'private_draft_archive_rpc_missing'; end if;
  if v_proc.prosecdef or pg_catalog.pg_get_userbyid(v_proc.proowner)<>'postgres'
   or v_proc.provolatile::text<>v_expected.volatility
   or not coalesce(v_proc.proconfig @> array['search_path=""'],false)
   or not pg_catalog.has_function_privilege('{backend}',v_proc.oid,'EXECUTE') then
   raise exception 'private_draft_archive_rpc_security_mismatch';
  end if;
  if pg_catalog.encode(pg_catalog.sha256(pg_catalog.convert_to(v_proc.prosrc,'UTF8')),'hex')<>v_expected.body_hash then
   raise exception 'private_draft_archive_rpc_source_mismatch';
  end if;
  foreach v_role in array array[{denied}] loop
   if pg_catalog.has_function_privilege(v_role,v_proc.oid,'EXECUTE') then
    raise exception 'private_draft_archive_rpc_browser_grant';
   end if;
  end loop;
  if exists(select 1 from pg_catalog.aclexplode(coalesce(v_proc.proacl,pg_catalog.acldefault('f',v_proc.proowner))) a
   where a.grantee=0 and a.privilege_type='EXECUTE') then
   raise exception 'private_draft_archive_rpc_public_grant';
  end if;
 end loop;
 select pg_catalog.pg_get_functiondef(pg_catalog.to_regprocedure('{schema}.edoc_save_compose_draft(text,text,text,integer,jsonb,text,boolean)')) into v_save;
 if v_save is null or pg_catalog.strpos(v_save,'if v_row.archived and not p_archived')=0 then
  raise exception 'private_draft_archive_autosave_guard_missing';
 end if;
end $private_draft_archive_gate$;
"""


def render_shared_forward():
    source = (ROOT / "supabase/migrations" / SOURCE).read_text()
    transformed = transform_sql(source)
    source_hash, transformed_hash = sha256_text(source), sha256_text(transformed)
    return f"""-- Generated by tools/private_draft_archive_shared_forward.py.
begin;
set local lock_timeout='5s';
set local statement_timeout='120s';
select pg_catalog.pg_advisory_xact_lock(1788103601,20261018);
do $preflight$
begin
 if pg_catalog.to_regclass('edoc_private.shared_project_migration_ledger') is null
  or pg_catalog.to_regprocedure('edoc.edoc_save_compose_draft(text,text,text,integer,jsonb,text,boolean)') is null
  or not exists(select 1 from pg_catalog.pg_roles where rolname='edoc_backend' and not rolbypassrls) then
  raise exception 'shared_private_draft_archive_preflight_failed';
 end if;
end $preflight$;
do $forward$
begin
 if exists(select 1 from edoc_private.shared_project_migration_ledger where file_name='{SOURCE}'
  and (source_sha256 is distinct from '{source_hash}' or transformed_sha256 is distinct from '{transformed_hash}'
   or bundle_version is distinct from '{BUNDLE_VERSION}')) then
  raise exception 'shared_private_draft_archive_hash_mismatch';
 end if;
 if not exists(select 1 from edoc_private.shared_project_migration_ledger where file_name='{SOURCE}') then
  execute $source$
{transformed}$source$;
  insert into edoc_private.shared_project_migration_ledger(file_name,source_sha256,transformed_sha256,bundle_version)
   values('{SOURCE}','{source_hash}','{transformed_hash}','{BUNDLE_VERSION}');
 end if;
end $forward$;
notify pgrst,'reload schema';
commit;
"""
