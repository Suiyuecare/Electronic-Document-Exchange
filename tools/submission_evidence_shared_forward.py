"""Hash-bound, fail-closed shared forward for atomic submission step metadata."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from tools.shared_supabase_bootstrap import ROOT, BUNDLE_VERSION, sha256_text, transform_sql

SOURCE = "20261014031923_atomic_submission_step_evidence_defaults.sql"
FORWARD_NAME = "20261014031923_shared_atomic_submission_step_evidence_defaults.sql"


def render_shared_forward() -> str:
    source = (ROOT / "supabase/migrations" / SOURCE).read_text()
    transformed = transform_sql(source)
    source_hash, transformed_hash = sha256_text(source), sha256_text(transformed)
    return f"""-- Generated by tools/submission_evidence_shared_forward.py; source hashes locked.
-- Only the existing submission RPC changes; no business rows, grants, or constraints change.
begin;
set local lock_timeout = '5s';
set local statement_timeout = '120s';
select pg_catalog.pg_advisory_xact_lock(1788103601, 20261014);
do $preflight$
begin
  if pg_catalog.to_regclass('edoc_private.shared_project_migration_ledger') is null
     or pg_catalog.to_regprocedure('edoc.edoc_commit_official_document_submission(jsonb)') is null
     or not exists(select 1 from pg_catalog.pg_roles where rolname='edoc_backend' and not rolbypassrls)
     or not exists(select 1 from edoc_private.shared_project_migration_ledger where file_name='20261012115431_editor_application_final_snapshot.sql') then
    raise exception 'shared_submission_evidence_preflight_failed';
  end if;
end $preflight$;
do $forward$
begin
  if exists(select 1 from edoc_private.shared_project_migration_ledger where file_name='{SOURCE}'
    and (source_sha256 is distinct from '{source_hash}' or transformed_sha256 is distinct from '{transformed_hash}'
      or bundle_version is distinct from '{BUNDLE_VERSION}')) then
    raise exception 'shared_submission_evidence_source_hash_mismatch';
  end if;
  if not exists(select 1 from edoc_private.shared_project_migration_ledger where file_name='{SOURCE}') then
    execute $source$
{transformed}$source$;
    insert into edoc_private.shared_project_migration_ledger(file_name,source_sha256,transformed_sha256,bundle_version)
      values('{SOURCE}','{source_hash}','{transformed_hash}','{BUNDLE_VERSION}');
  end if;
end $forward$;
notify pgrst, 'reload schema';
commit;
"""


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = render_shared_forward()
    if args.check:
        target = ROOT / "supabase/shared-project-migrations" / FORWARD_NAME
        matches = target.is_file() and target.read_text() == rendered
        print(json.dumps({"matches": matches, "file": FORWARD_NAME}))
        raise SystemExit(0 if matches else 1)
    print(rendered, end="")
